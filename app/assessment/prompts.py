def wrap_resume(text: str) -> str:
    # Закрывающий тег внутри резюме не должен разорвать блок данных.
    safe = text.replace("</resume_text>", "</resume_text_>")
    return f"<resume_text>\n{safe}\n</resume_text>"


def card_user(text: str) -> str:
    return "Извлеки карточку кандидата.\n\n" + wrap_resume(text)


def formal_user(text: str, *, experience: list[dict] | None, alternatives: list[dict]) -> str:
    parts = ["Проверь требования к должности по резюме."]
    if experience:
        parts.append(
            "Стаж: перечисли в periods все периоды работы, стажировок и проектов с датами как в тексте и видом записи. "
            "Если в тексте есть фраза об общем стаже, заполни statement. Если кандидат прямо пишет, что опыта нет, "
            "заполни no_experience_quote. Описания релевантного опыта (для поля relevant): "
            + json.dumps(experience, ensure_ascii=False)
        )
    if alternatives:
        parts.append(
            "Образование: для каждой альтернативы верни статус и цитату. Альтернативы: "
            + json.dumps(alternatives, ensure_ascii=False)
        )
    return "\n\n".join(parts) + "\n\n" + wrap_resume(text)


def competency_user(text: str, *, competency: str, indicators: list[dict]) -> str:
    return (
        f"Компетенция: {competency}. Для каждого индикатора верни статус и цитату. Индикаторы: "
        + json.dumps(indicators, ensure_ascii=False)
        + "\n\n"
        + wrap_resume(text)
    )
